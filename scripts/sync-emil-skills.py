#!/usr/bin/env python3
"""Vendor Emil Kowalski's skills (github.com/emilkowalski/skills) into this harness.

Same script in xxarupakaxx/.codex and xxarupakaxx/.claude. It writes flat
skills/<name>/ folders, because both Codex and Claude Code discover
skills/<name>/SKILL.md and upstream skills refer to each other by bare name.

Skills listed in LOCAL_ADAPTATIONS are the user's own Japanese adaptations
(collection emilkowalski-ja-2026-07). This script never touches them.

Per managed skill it adds SOURCE.md and LICENSE (upstream MIT). The root
performance-cheatsheet.md goes into animation-performance/. On Codex, skills
with `disable-model-invocation: true` also get agents/openai.yaml with
`allow_implicit_invocation: false`. Nothing else is changed.

Usage:
  python3 scripts/sync-emil-skills.py               # fetch upstream main, re-vendor
  python3 scripts/sync-emil-skills.py --ref <sha>
  python3 scripts/sync-emil-skills.py --source DIR  # existing checkout
  python3 scripts/sync-emil-skills.py --check       # compare with the commit in the lock file
Network access is only git fetch of the upstream repository. No upstream code is executed.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

REPO = "https://github.com/emilkowalski/skills"
ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
LOCK = Path(__file__).resolve().with_suffix(".lock.json")
HARNESS = "claude" if (ROOT / "CLAUDE.md").exists() else "codex"
COLLECTION = "emilkowalski-2026-10"
LOCAL_ADAPTATIONS = {
    "animation-vocabulary", "apple-design", "emil-design-eng",
    "find-animation-opportunities", "improve-animations", "review-animations",
}
EXTRA = {"animation-performance": ["performance-cheatsheet.md"]}


def run(cmd: list[str], cwd: Path | None = None) -> str:
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def fetch(ref: str, workdir: Path) -> Path:
    co = workdir / "skills"
    print(f"fetch: {REPO} {ref}", file=sys.stderr)
    run(["git", "init", "-q", str(co)])
    run(["git", "fetch", "-q", "--depth", "1", REPO, ref], cwd=co)
    run(["git", "checkout", "-q", "FETCH_HEAD"], cwd=co)
    print("fetch: done", file=sys.stderr)
    return co


def source_md(name: str, sha: str, retrieved: str, extras: list[str], yaml: bool) -> str:
    notes = []
    if extras:
        notes.append(f"upstream root の {', '.join(f'`{e}`' for e in extras)} をこのSkillに同梱した（upstreamのSkill本文からは参照されていない）。")
    if yaml:
        notes.append("`disable-model-invocation: true` のCodex相当として `agents/openai.yaml`（`allow_implicit_invocation: false`）を追加した。")
    adaptation = "\n".join(f"- {n}" for n in notes) or "- なし。upstreamの内容をそのまま置いている。"
    return f"""# Source

- Repository: {REPO}
- Commit: `{sha}`
- Path: `skills/{name}`
- License: MIT（`LICENSE`、Copyright (c) 2026 Emil Kowalski）
- Retrieved: {retrieved}
- Collection: `{COLLECTION}`
- Relation: upstream verbatim copy
- Sync: `python3 scripts/sync-emil-skills.py`（`--check` で差分確認）

## Local adaptation

{adaptation}

skill-governance の隔離審査・receiptは未作成（Linux hostで導入したため）。
"""


def render(src: Path, sha: str, retrieved: str) -> dict[str, dict[str, bytes]]:
    out: dict[str, dict[str, bytes]] = {}
    license_bytes = (src / "LICENSE").read_bytes()
    for skill_md in sorted((src / "skills").glob("*/SKILL.md")):
        name = skill_md.parent.name
        if name in LOCAL_ADAPTATIONS:
            continue
        files = {p.relative_to(skill_md.parent).as_posix(): p.read_bytes()
                 for p in sorted(skill_md.parent.rglob("*")) if p.is_file()}
        extras = EXTRA.get(name, [])
        for e in extras:
            files[e] = (src / e).read_bytes()
        disabled = b"\ndisable-model-invocation: true\n" in skill_md.read_bytes().split(b"\n---", 1)[0] + b"\n"
        yaml = HARNESS == "codex" and disabled
        if yaml:
            files["agents/openai.yaml"] = (b"# Generated by scripts/sync-emil-skills.py from `disable-model-invocation: true`.\n"
                                           b"policy:\n  allow_implicit_invocation: false\n")
        files["LICENSE"] = license_bytes
        files["SOURCE.md"] = source_md(name, sha, retrieved, extras, yaml).encode()
        out[name] = files
    return out


def disk(name: str) -> dict[str, bytes]:
    d = SKILLS / name
    return {p.relative_to(d).as_posix(): p.read_bytes() for p in d.rglob("*") if p.is_file()} if d.exists() else {}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref")
    ap.add_argument("--source", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    lock = json.loads(LOCK.read_text()) if LOCK.exists() else {}
    with tempfile.TemporaryDirectory() as tmp:
        if args.source:
            src = args.source.resolve()
        else:
            ref = args.ref or (lock.get("commit") if args.check else None) or "main"
            src = fetch(ref, Path(tmp))
        sha = run(["git", "rev-parse", "HEAD"], cwd=src)
        retrieved = lock.get("retrieved") if args.check and lock else date.today().isoformat()
        rendered = render(src, sha, retrieved)
        upstream_names = sorted(p.parent.name for p in (src / "skills").glob("*/SKILL.md"))

        if args.check:
            drift = [n for n, files in rendered.items() if disk(n) != files]
            drift += [f"{n} (no longer upstream)" for n in lock.get("managed", []) if n not in rendered]
            for n in drift:
                print(f"DRIFT skills/{n}")
            print("emil skills are up to date." if not drift else f"emil skills drift: {len(drift)} (commit {sha})")
            return 1 if drift else 0

        for n in lock.get("managed", []):
            if n not in rendered and (SKILLS / n).exists():
                print(f"note: skills/{n} is no longer upstream; left in place, remove it by hand if intended")
        for n, files in rendered.items():
            d = SKILLS / n
            if d.exists():
                if n not in lock.get("managed", []):
                    print(f"skip: skills/{n} exists and is not managed by this script")
                    continue
                shutil.rmtree(d)
            for rel, data in files.items():
                (d / rel).parent.mkdir(parents=True, exist_ok=True)
                (d / rel).write_bytes(data)
        managed = sorted(n for n in rendered if n in lock.get("managed", []) or ((SKILLS / n / "SOURCE.md").exists() and (SKILLS / n / "SOURCE.md").read_bytes() == rendered[n]["SOURCE.md"]))
        lock = {
            "repository": REPO, "commit": sha, "retrieved": retrieved, "license": "MIT",
            "collection": COLLECTION, "managed": managed,
            "local_adaptations": sorted(set(upstream_names) & LOCAL_ADAPTATIONS),
        }
        LOCK.write_text(json.dumps(lock, indent=2, ensure_ascii=False) + "\n")
        print(f"emil skills {sha[:12]}: {len(managed)} managed, {len(lock['local_adaptations'])} local adaptations left untouched")
    return 0


if __name__ == "__main__":
    sys.exit(main())
